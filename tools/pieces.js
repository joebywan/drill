/**
 * Writes assets/pieces/drill.svg, Drill's own piece set: `node tools/pieces.js`.
 *
 * Built like the cast: flat fills, chunky rounded forms, one shade tone as a crescent on the
 * right, sitting on a round plinth. A soft edge in a darker tone (never black ink) keeps pale
 * pieces readable on pale squares. Each piece is one silhouette path drawn three times: edge,
 * body, then the shade (the body nudged up-left, clipped to the silhouette).
 * cm-chessboard looks pieces up by id (wk, bq…) on a 40 x 40 tile.
 */
import { writeFileSync } from 'node:fs';

const rr = (x, y, w, h, r = Math.min(w, h) / 2) =>
  `M${x + r} ${y}H${x + w - r}A${r} ${r} 0 0 1 ${x + w} ${y + r}V${y + h - r}A${r} ${r} 0 0 1 ${x + w - r} ${y + h}`
  + `H${x + r}A${r} ${r} 0 0 1 ${x} ${y + h - r}V${y + r}A${r} ${r} 0 0 1 ${x + r} ${y}Z`;
const circle = (cx, cy, r) => `M${cx - r} ${cy}A${r} ${r} 0 1 1 ${cx + r} ${cy}A${r} ${r} 0 1 1 ${cx - r} ${cy}Z`;
const BASE = rr(9, 29.5, 22, 6, 3);
// A flared foot from a collar at `top` down to the plinth.
// Every subpath runs clockwise: an anticlockwise one would punch a hole where it overlaps.
const skirt = (top, half = 4.5) => `M${20 + half} ${top}Q${20.5 + half} ${top + 4} 28 30H12Q${19.5 - half} ${top + 4} ${20 - half} ${top}Z`;

const SHAPES = {
  p: circle(20, 12.5, 6) + rr(13.5, 18, 13, 4) + skirt(21, 4) + BASE,
  r: rr(10, 5.5, 6, 7, 2) + rr(17, 5.5, 6, 7, 2) + rr(24, 5.5, 6, 7, 2) + rr(10, 9.5, 20, 7, 2.5)
    + 'M13.5 16H26.5L27 30H13Z' + rr(11.5, 15.5, 17, 3.5) + BASE,
  b: circle(20, 4.6, 2.6) + 'M20 6.5C27 10.5 28.5 16 25.5 20.5H14.5C11.5 16 13 10.5 20 6.5Z'
    + rr(13, 19.5, 14, 4) + skirt(23, 4) + BASE,
  q: circle(9.5, 10, 2.5) + circle(15, 7.5, 2.5) + circle(20, 5.6, 2.7) + circle(25, 7.5, 2.5) + circle(30.5, 10, 2.5)
    + 'M9.5 10.5Q13 17 15 8Q17.5 15.5 20 6.5Q22.5 15.5 25 8Q27 17 30.5 10.5L27 22H13Z' + rr(12, 21, 16, 4) + skirt(24.5, 5) + BASE,
  k: rr(18.1, 1, 3.8, 10, 1.9) + rr(14.8, 3.6, 10.4, 3.8, 1.9)
    + 'M11.5 13.5C11 9.5 16 9 20 11.5C24 9 29 9.5 28.5 13.5L26.5 22H13.5Z' + rr(12, 21, 16, 4) + skirt(24.5, 5) + BASE,
  // The knight: a round-muzzled pony looking left, ears up, mane down its back.
  n: 'M13 30C14.5 27 16.5 24 17.5 20.5C15.5 21 14 22.5 11.5 22.5C8 22.5 6.5 19.5 8 16.5'
    + 'C11 10.5 15.5 7 21.5 7L26 4L25 9.5C29.5 14.5 30.5 22.5 28.5 30Z' + circle(11.2, 19.2, 3.6) + 'M18 9L19.2 3.4Q21.8 4.6 23 8.5Z' + BASE,
};

const COLOURS = {
  w: { edge: '#5F6B7C', body: '#F7F9FC', shade: '#CDD5E0', eye: '#2B3340' },
  b: { edge: '#151B24', body: '#435064', shade: '#2C3646', eye: '#151B24' },
};

// Details drawn over the body, per piece; `c` is the colour set. `collar` underlines a collar.
const collar = (y, half, c) => `<path d="M${20 - half} ${y}Q20 ${y + 1} ${20 + half} ${y}" fill="none" stroke="${c.shade}" stroke-width="1.5" stroke-linecap="round"/>`;
const DETAIL = {
  p: (c) => collar(22.3, 5, c),
  r: (c) => collar(19.3, 6.8, c),
  b: (c) => `<path d="M22.4 10.5L18.8 15" stroke="${c.edge}" stroke-width="1.8" stroke-linecap="round"/>` + collar(23.8, 5.5, c),
  k: (c) => `<path d="M14.5 19.5Q20 17.5 25.5 19.5" fill="none" stroke="${c.shade}" stroke-width="1.6" stroke-linecap="round"/>` + collar(25.3, 6.5, c),
  q: (c) => `<circle cx="20" cy="18.5" r="1.6" fill="${c.shade}"/>` + collar(25.3, 6.5, c),
  n: (c) => [
    // mane: a few round tufts down the back of the neck
    ...[[25.5, 11.5], [27.2, 15.5], [28, 20], [28, 24.5]].map(([x, y]) => `<circle cx="${x}" cy="${y}" r="2.3" fill="${c.shade}"/>`),
    `<ellipse cx="17" cy="13" rx="2.6" ry="2.9" fill="#fff"/>`,
    `<circle cx="16.4" cy="13.4" r="1.6" fill="${c.eye}"/><circle cx="16" cy="12.8" r=".55" fill="#fff"/>`,
    `<circle cx="8.8" cy="18.6" r=".9" fill="${c.edge}"/>`,
    `<path d="M10.5 22Q12.8 22.3 14.3 21.2" fill="none" stroke="${c.edge}" stroke-width="1" stroke-linecap="round"/>`,
  ].join(''),
};

const defs = Object.entries(SHAPES).map(([t, d]) =>
  `<path id="s${t}" d="${d}"/><clipPath id="c${t}"><use href="#s${t}"/></clipPath>`).join('\n  ');
const pieces = ['w', 'b'].flatMap((side) => Object.keys(SHAPES).map((t) => {
  const c = COLOURS[side];
  return `<g id="${side}${t}">`
    + `<use href="#s${t}" fill="${c.edge}" stroke="${c.edge}" stroke-width="2.4" stroke-linejoin="round"/>`
    + `<g clip-path="url(#c${t})"><use href="#s${t}" fill="${c.shade}"/><use href="#s${t}" fill="${c.body}" transform="translate(-2.2 -1)"/></g>`
    + (DETAIL[t]?.(c) || '') + '</g>';
}));

writeFileSync(new URL('../assets/pieces/drill.svg', import.meta.url), `<?xml version="1.0" encoding="UTF-8"?>
<!-- Drill's piece set, drawn for Drill. Generated by tools/pieces.js: edit that, not this. -->
<svg width="40" height="40" viewBox="0 0 40 40" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">
  <defs>
  ${defs}
  </defs>
  ${pieces.join('\n  ')}
</svg>
`);
