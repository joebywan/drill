/**
 * Drill's icon: Lumi's head, as src/cast/lumi.js draws her, peeking up from the bottom of a
 * garden-green square. Run `node tools/icon.js` after Lumi changes; it writes, from that one drawing,
 *   assets/icon.svg                    the web favicon (rounded square)
 *   assets/icon-512.png                the manifest's maskable icon and the Play listing icon
 *   android/.../drawable/ic_launcher_fg.xml, ic_launcher_mono.xml   the adaptive icon's layers
 * The Android layers are vector drawables converted from Lumi's own SVG elements, so nothing is redrawn.
 */
import { writeFileSync } from 'node:fs';
import { chromium } from 'playwright';
import { lumi } from '../src/cast/lumi.js';

const ROOT = new URL('..', import.meta.url).pathname;
const RES = `${ROOT}android/app/src/main/res`;
const GREEN = '#2F7D4F'; // --accent in styles.css: the garden green

// Lumi's body and head (no shadow, feet or flippers), on a 108-unit adaptive icon canvas: her face
// sits inside the 66-unit safe zone, and her body runs off the bottom under the mask.
const S = 0.92, X = 54 - 50 * S, Y = 62 - 42 * S;
const art = lumi('teach').replace(/<g data-part="arms">.*?<\/g>\s*<\/g>/s, '</g>');

const attrs = (s) => Object.fromEntries([...s.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const n = (k) => Number(k);
const oval = (cx, cy, rx, ry) => `M${cx - rx},${cy} a${rx},${ry} 0 1,0 ${2 * rx},0 a${rx},${ry} 0 1,0 ${-2 * rx},0 Z`;
function rectPath({ x, y, width: w, height: h, rx = 0 }) {
  [x, y, w, h, rx] = [x, y, w, h, rx].map(n);
  if (!rx) return `M${x},${y} h${w} v${h} h${-w} Z`;
  return `M${x + rx},${y} h${w - 2 * rx} a${rx},${rx} 0 0,1 ${rx},${rx} v${h - 2 * rx} a${rx},${rx} 0 0,1 ${-rx},${rx} h${-(w - 2 * rx)} a${rx},${rx} 0 0,1 ${-rx},${-rx} v${-(h - 2 * rx)} a${rx},${rx} 0 0,1 ${rx},${-rx} Z`;
}

/** Lumi's drawing as plain shapes: { d, fill } or { d, stroke, width }, in her own 100x120 units. */
const shapes = [...art.matchAll(/<(ellipse|circle|path|rect)\s([^>]*?)\/>/g)].flatMap(([, tag, raw]) => {
  const a = attrs(raw);
  if (a['data-part'] === 'shadow') return [];
  if (/rotate\((?!0 )/.test(a.transform || '')) return []; // the feet, tilted, below the mask anyway
  const d = tag === 'path' ? a.d
    : tag === 'rect' ? rectPath(a)
    : oval(n(a.cx), n(a.cy), n(a.rx ?? a.r), n(a.ry ?? a.r));
  return [{ d, fill: a.fill === 'none' ? null : a.fill, stroke: a.stroke, width: a['stroke-width'], alpha: a.opacity }];
});

const hex = (c) => {
  const h = c.replace('#', '');
  return `#${(h.length === 3 ? [...h].map((x) => x + x).join('') : h).toUpperCase()}`;
};
const vector = (paths) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon.js from Lumi (src/cast/lumi.js). Edit Lumi, then run the tool. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="${X}" android:translateY="${Y}" android:scaleX="${S}" android:scaleY="${S}">
${paths.join('\n')}
    </group>
</vector>
`;
const fg = shapes.map((s) => s.fill
  ? `        <path android:pathData="${s.d}" android:fillColor="${hex(s.fill)}"${s.alpha ? ` android:fillAlpha="${s.alpha}"` : ''} />`
  : `        <path android:pathData="${s.d}" android:strokeColor="${hex(s.stroke)}" android:strokeWidth="${s.width}" android:strokeLineCap="round"${s.alpha ? ` android:strokeAlpha="${s.alpha}"` : ''} />`);

// Themed icons use only the monochrome layer's shape: Lumi's outline with her eyes, nose and brows
// cut out (even-odd) and her pupils put back. Her smile is a stroke, which can't be cut, so it's left out.
const outline = shapes.find((s) => s.d.startsWith('M50 14'));
const eyes = shapes.filter((s) => s.fill === '#fff' && /a6,7/.test(s.d));
const pupils = shapes.filter((s) => s.fill === '#1E1B2E' && /a3\.3,3\.3/.test(s.d));
const nose = shapes.find((s) => /a4,3 /.test(s.d));
const brows = shapes.filter((s) => /a1\.8,1\.8/.test(s.d));
if (!outline || eyes.length !== 2 || pupils.length !== 2 || !nose || brows.length !== 2) throw new Error('Lumi has changed shape: update the monochrome layer in tools/icon.js');
const mono = [
  `        <path android:fillType="evenOdd" android:fillColor="#FFFFFFFF" android:pathData="${[outline, ...eyes, nose, ...brows].map((s) => s.d).join(' ')}" />`,
  ...pupils.map((s) => `        <path android:fillColor="#FFFFFFFF" android:pathData="${s.d}" />`),
];

writeFileSync(`${RES}/drawable/ic_launcher_fg.xml`, vector(fg));
writeFileSync(`${RES}/drawable/ic_launcher_mono.xml`, vector(mono));

// The web's copy: the same elements, as SVG, on the same canvas.
const svg = (rx, box = '0 0 108 108') => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box}"><rect width="108" height="108" rx="${rx}" fill="${GREEN}"/>`
  + `<g transform="translate(${X} ${Y}) scale(${S})">${shapes.map((s) => `<path d="${s.d}" ${s.fill ? `fill="${s.fill}"` : `fill="none" stroke="${s.stroke}" stroke-width="${s.width}" stroke-linecap="round"`}${s.alpha ? ` opacity="${s.alpha}"` : ''}/>`).join('')}</g></svg>\n`;
// The favicon shows what a launcher shows: the middle 72 units.
writeFileSync(`${ROOT}assets/icon.svg`, svg(0, '18 18 72 72').replace('<rect width="108" height="108" rx="0"', '<rect x="18" y="18" width="72" height="72" rx="16"'));

// Full bleed, no corners: Play and maskable icons are masked by whoever shows them.
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 512, height: 512 } });
await page.setContent(`<style>body{margin:0}svg{display:block;width:512px;height:512px}</style>${svg(0)}`);
await page.screenshot({ path: `${ROOT}assets/icon-512.png`, omitBackground: false });
await browser.close();
console.log('wrote assets/icon.svg, assets/icon-512.png, ic_launcher_fg.xml, ic_launcher_mono.xml');
